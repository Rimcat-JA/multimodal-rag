"""Compare C-ft trained on the v1 and v2 training data, each with seeds 42, 43 and 44.

Run with:  uv run python scripts/compare_train_data.py

v1 is configs/finetune_c.toml, v2 is configs/finetune_c_v2.toml (more companies and
more queries per page, changed together). The comparison fixed before training is
the mean validation MRR@10. The evaluation set is reported per seed and on average.
For the average, each question's score is averaged over the three seeds and the
difference is bootstrapped over questions, so the interval does not cover the seed.

Writes results/c-ft_v2.md. It does not replace the C-ft used in the READMEs.
"""

from statistics import mean

from compare_methods import METRICS, METRIC_LABELS, latest_clean_run
from compare_seeds import RESULTS, ROOT, latest_clean, seed_rows, v1_dirs

from multimodal_rag.eval.compare import answerable_within, paired_bootstrap, reciprocal_rank
from multimodal_rag.evalset import load_questions

SEEDS = [42, 43, 44]


def fmt(t: tuple[float, float, float]) -> str:
    return f"{t[0]:+.3f} [{t[1]:+.3f}, {t[2]:+.3f}]"


def per_question_mean(rows: list[dict], qids: list[str], score) -> list[float]:
    return [mean(score(r["ranks"][q]) for r in rows) for q in qids]


def table_rows(name: str, rows: list[dict]) -> list[str]:
    lines = [f"| {name} | {r['seed']} | {r['val_mrr']:.3f} | " + " | ".join(f"{r['overall'][m]:.3f}" for m in METRICS)
             + f" | {fmt(r['mrr_vs_c'])} |" for r in rows]
    lines.append(f"| {name} | mean | {mean(r['val_mrr'] for r in rows):.3f} | "
                 + " | ".join(f"{mean(r['overall'][m] for r in rows):.3f}" for m in METRICS)
                 + f" | {mean(r['mrr_vs_c'][0] for r in rows):+.3f} |")
    return lines


def main() -> None:
    c_run = latest_clean_run("C")
    v2_dirs = [latest_clean(f) for f in sorted((RESULTS / "c-ft-v2").glob("seed*"))]
    if c_run is None or None in v2_dirs:
        raise SystemExit("need a clean run of C and of every v2 seed")
    _, questions = load_questions(ROOT / "eval" / "questions.csv")
    qids = [q["qid"] for q in questions]
    v1, v2 = seed_rows(v1_dirs(), c_run, qids), seed_rows(v2_dirs, c_run, qids)
    for name, rows in (("v1", v1), ("v2", v2)):
        if [r["seed"] for r in rows] != SEEDS:
            raise SystemExit(f"{name} has seeds {[r['seed'] for r in rows]}, expected {SEEDS}")

    mrr = paired_bootstrap(per_question_mean(v1, qids, reciprocal_rank), per_question_mean(v2, qids, reciprocal_rank))
    within_1 = lambda rank: answerable_within(rank, 1)
    r1 = paired_bootstrap(per_question_mean(v1, qids, within_1), per_question_mean(v2, qids, within_1))
    lines = [
        "# C-ft with more training data", "",
        "Generated by `scripts/compare_train_data.py`; do not edit by hand.",
        "v1: 8 training companies, 2 queries per page. v2: 20 training companies, 4 queries per page. "
        "The two changes were made together, so their effects can't be told apart. "
        "Both use the same validation queries, so validation scores compare directly. "
        "Each model was evaluated once. The READMEs' headline C-ft stays v1, seed 42.", "",
        "| Data | Seed | Validation MRR@10 | " + " | ".join(METRIC_LABELS[m] for m in METRICS) + " | MRR − C [95% interval] |",
        "|---" * (len(METRICS) + 4) + "|",
        *table_rows("v1", v1), *table_rows("v2", v2), "",
        "Mean validation MRR@10, v2 − v1 (the comparison fixed before training): "
        f"{mean(r['val_mrr'] for r in v2) - mean(r['val_mrr'] for r in v1):+.3f}.", "",
        "Evaluation set, v2 − v1, each question averaged over the three seeds "
        "(paired bootstrap over questions, 10,000 resamples, seed 0; the interval does not cover the seed):", "",
        f"- MRR: {fmt(mrr)}", f"- Recall@1: {fmt(r1)}", "",
        "| Data | Seed | Evaluation run | Training run | Training run from committed code |", "|---|---|---|---|---|",
    ]
    lines += [f"| {name} | {r['seed']} | `{r['eval_run']}` | `{r['train_run']}` | {'no' if r['train_dirty'] else 'yes'} |"
              for name, rows in (("v1", v1), ("v2", v2)) for r in rows]
    out = RESULTS / "c-ft_v2.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))
    print(f"\nwrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
