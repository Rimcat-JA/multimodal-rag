"""Sort each method's retrieval misses into failure types.

Run with:  uv run python scripts/analyze_failures.py

Uses the same runs as scripts/compare_methods.py (latest clean run per method)
and writes results/failure_analysis.md. A question is a miss when the top 5
pages don't cover every gold group (rank > 5 or never). Each miss is sorted by
the top-1 page:
    other company   the top page is from a different company
    other deck      right company, but a deck that has no gold page
    other page      right deck, wrong page
B2 has one more type, "no caption": a required gold group has no page with
figures (captioning failed or found none), so B2 can't return it.
"""

import csv
import json
from pathlib import Path

from compare_methods import LABELS, METHODS, latest_clean_run  # scripts/ is on sys.path

from multimodal_rag.evalset import load_questions, parse_gold

ROOT = Path(__file__).resolve().parent.parent
TOP = 5
TYPES = ["other company", "other deck", "other page", "no caption"]


def company(page_id: str) -> str:
    return page_id.split("/")[0]


def deck(page_id: str) -> str:
    return page_id.rsplit("/", 1)[0]


def main() -> None:
    _, questions = load_questions(ROOT / "eval" / "questions.csv")
    runs = {m: d for m in METHODS if (d := latest_clean_run(m))}
    b2_captions = None
    if "B2" in runs:
        cache = json.loads((runs["B2"] / "run.json").read_text(encoding="utf-8"))["captions"]["cache"]
        b2_captions = ROOT / cache

    def has_figures(page_id: str) -> bool:
        return bool(json.loads((b2_captions / f"{page_id}.json").read_text(encoding="utf-8"))["figures"])

    rows, counts, top1_company = [], {}, {}
    for m, run_dir in runs.items():
        with (run_dir / "per_question.csv").open(encoding="utf-8") as f:
            per_q = {r["qid"]: r for r in csv.DictReader(f)}
        counts[m] = dict.fromkeys(TYPES, 0)
        top1_company[m] = 0
        for q in questions:
            r = per_q[q["qid"]]
            groups = parse_gold(q["gold_pages"])
            gold = [p for g in groups for p in g]
            top1 = r["top10"].split(";")[0]
            top1_company[m] += company(top1) == company(gold[0])
            rank = int(r["rank"]) if r["rank"] else None
            if rank is not None and rank <= TOP:
                continue
            if m == "B2" and any(not any(has_figures(p) for p in g) for g in groups):
                kind = "no caption"
            elif company(top1) != company(gold[0]):
                kind = "other company"
            elif deck(top1) not in {deck(p) for p in gold}:
                kind = "other deck"
            else:
                kind = "other page"
            counts[m][kind] += 1
            rows.append({"method": m, "qid": q["qid"], "evidence": q["evidence"], "q_type": q["q_type"],
                         "rank": r["rank"] or "never", "type": kind, "top1": top1})

    n = len(questions)
    lines = [
        "# Retrieval failure analysis",
        "",
        "Generated by `scripts/analyze_failures.py`; do not edit by hand. Same runs as `results/comparison.md`.",
        f"A miss is a question whose top {TOP} pages don't cover every gold group. Each miss is typed by the top-1 page.",
        "",
        "## Is the top page from the right company?",
        "",
        "| Method | Top-1 page from the asked company |",
        "|---|---|",
    ]
    lines += [f"| {LABELS[m]} | {top1_company[m]}/{n} |" for m in runs]
    lines += ["", f"## Misses by type (top {TOP})", "", "| Method | Misses | " + " | ".join(TYPES) + " |",
              "|---|---|" + "---|" * len(TYPES)]
    lines += [f"| {LABELS[m]} | {sum(counts[m].values())} | " + " | ".join(str(counts[m][t]) for t in TYPES) + " |"
              for m in runs]
    lines += ["", "## Every miss", "", "| Method | Question | Evidence | Question type | Rank | Type | Top-1 page |",
              "|---|---|---|---|---|---|---|"]
    lines += [f"| {r['method']} | {r['qid']} | {r['evidence']} | {r['q_type']} | {r['rank']} | {r['type']} | `{r['top1']}` |"
              for r in rows]
    out = ROOT / "results" / "failure_analysis.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines[:20]))


if __name__ == "__main__":
    main()
