"""Compare C-ft training runs that differ only in the training seed.

Run with:  uv run python scripts/compare_seeds.py

Reads method C's run and every C-ft run on the evaluation set: the main one in
results/method_c-ft/ (the one compare_methods.py and the READMEs use) and the
extra seeds in results/c-ft_seeds/seed<n>/. Only runs made from committed code
(git.dirty is false) are used, the latest per folder. Each evaluation run is
matched to its training run in results/finetune/ by the model's SHA-256, which
gives the seed and the validation companies' MRR@10.

Writes results/c-ft_seeds.md. It reports every seed; it does not pick one.
"""

import json
from pathlib import Path
from statistics import mean

from compare_methods import METRICS, METRIC_LABELS, latest_clean_run, load_ranks, scores

from multimodal_rag.eval.compare import answerable_within, paired_bootstrap, reciprocal_rank
from multimodal_rag.evalset import load_questions

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
VAL_METRIC = "val_maxsim_mrr@10"  # evaluator key (the trainer logs it with an "eval_" prefix)


def latest_clean(folder: Path) -> Path | None:
    runs = sorted(folder.glob("*/run.json"))
    clean = [r.parent for r in runs if not json.loads(r.read_text(encoding="utf-8"))["git"]["dirty"]]
    return clean[-1] if clean else None


def training_runs() -> dict[str, dict]:
    """Training run.json contents keyed by the saved model's SHA-256."""
    out = {}
    for path in sorted((RESULTS / "finetune").glob("*/run.json")):
        meta = json.loads(path.read_text(encoding="utf-8"))
        out[meta["model_sha256"]] = meta | {"dir": path.parent.relative_to(ROOT).as_posix()}
    return out


def main() -> None:
    c_run = latest_clean_run("C")
    ft_dirs = [d for d in [latest_clean_run("C-ft")] + [latest_clean(f) for f in sorted((RESULTS / "c-ft_seeds").glob("seed*"))] if d]
    if c_run is None or not ft_dirs:
        raise SystemExit("need a clean run of C and at least one of C-ft")

    _, questions = load_questions(ROOT / "eval" / "questions.csv")
    qids = [q["qid"] for q in questions]
    c_meta = json.loads((c_run / "run.json").read_text(encoding="utf-8"))
    c_ranks = load_ranks(c_run)
    trainings = training_runs()

    rows = []
    for d in ft_dirs:
        meta = json.loads((d / "run.json").read_text(encoding="utf-8"))
        for key in ("eval_set", "pages"):
            if meta[key]["sha256"] != c_meta[key]["sha256"]:
                raise SystemExit(f"{d} uses a different {key} from {c_run}")
        training = trainings.get(meta["config"]["model_sha256"])
        if training is None:
            raise SystemExit(f"no training run in results/finetune/ saved the model evaluated in {d}")
        ranks = load_ranks(d)
        overall = scores([ranks[q] for q in qids])
        for metric in METRICS:  # the recomputed numbers must agree with what the run itself reported
            if abs(overall[metric] - meta["summary"][metric]) > 1e-12:
                raise SystemExit(f"{d} {metric}: recomputed {overall[metric]} != run.json {meta['summary'][metric]}")
        rows.append({
            "seed": training["config"]["train"]["seed"], "eval_run": d.relative_to(ROOT).as_posix(),
            "train_run": training["dir"], "commit": meta["git"]["commit"][:7],
            "val_mrr": training["validation_after"][VAL_METRIC], "overall": overall,
            "mrr_vs_c": paired_bootstrap([reciprocal_rank(c_ranks[q]) for q in qids], [reciprocal_rank(ranks[q]) for q in qids]),
            "r1_vs_c": paired_bootstrap([answerable_within(c_ranks[q], 1) for q in qids], [answerable_within(ranks[q], 1) for q in qids]),
        })
    rows.sort(key=lambda r: r["seed"])
    if len({r["seed"] for r in rows}) != len(rows):
        raise SystemExit(f"two C-ft runs share a seed: {[r['seed'] for r in rows]}")

    c_overall = scores([c_ranks[q] for q in qids])
    fmt = lambda t: f"{t[0]:+.3f} [{t[1]:+.3f}, {t[2]:+.3f}]"
    lines = [
        "# C-ft across training seeds", "",
        "Generated by `scripts/compare_seeds.py`; do not edit by hand.",
        f"Each row is one training run with the same data and settings except `[train] seed`, evaluated once on "
        f"`eval/questions.csv` (sha256 `{c_meta['eval_set']['sha256'][:12]}`, {len(qids)} questions). "
        "The seed-42 run is the C-ft used in the READMEs; it was fixed before the other seeds were trained.", "",
        "| Seed | Validation MRR@10 | " + " | ".join(METRIC_LABELS[m] for m in METRICS)
        + " | MRR − C [95% interval] | Recall@1 − C [95% interval] |",
        "|---" * (len(METRICS) + 4) + "|",
    ]
    for r in rows:
        lines.append(f"| {r['seed']} | {r['val_mrr']:.3f} | " + " | ".join(f"{r['overall'][m]:.3f}" for m in METRICS)
                     + f" | {fmt(r['mrr_vs_c'])} | {fmt(r['r1_vs_c'])} |")
    lines.append("| mean | " + f"{mean(r['val_mrr'] for r in rows):.3f} | "
                 + " | ".join(f"{mean(r['overall'][m] for r in rows):.3f}" for m in METRICS)
                 + f" | {mean(r['mrr_vs_c'][0] for r in rows):+.3f} | {mean(r['r1_vs_c'][0] for r in rows):+.3f} |")
    lines.append("| range | " + f"{max(r['val_mrr'] for r in rows) - min(r['val_mrr'] for r in rows):.3f} | "
                 + " | ".join(f"{max(r['overall'][m] for r in rows) - min(r['overall'][m] for r in rows):.3f}" for m in METRICS)
                 + " | | |")
    lines.append(f"| C (not fine-tuned) | – | " + " | ".join(f"{c_overall[m]:.3f}" for m in METRICS) + " | | |")
    lines += ["", "Intervals: paired bootstrap over questions (10,000 resamples, seed 0), as in `results/comparison.md`. "
              "They cover which questions were asked, not the training seed; the spread across rows shows the latter.", "",
              "| Seed | Evaluation run | Training run | Commit |", "|---|---|---|---|"]
    lines += [f"| {r['seed']} | `{r['eval_run']}` | `{r['train_run']}` | `{r['commit']}` |" for r in rows]
    out = RESULTS / "c-ft_seeds.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))
    print(f"\nwrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
